def _set_run_font(run, east=SONG, ascii_font="Times New Roman", size=11, bold=False):
    run.font.name = ascii_font
    run._element.rPr.rFonts.set(qn("w:eastAsia"), east)
    run.font.size = Pt(size)
    run.font.bold = bold


def add_para(doc, text, size=11, bold=False, east=SONG, align=None, space_after=6, indent=True):
    p = doc.add_paragraph()
    if indent:
        p.paragraph_format.first_line_indent = Pt(size * 2)
    p.paragraph_format.space_after = Pt(space_after)
    if align is not None:
        p.alignment = align
    r = p.add_run(text)
    _set_run_font(r, east=east, size=size, bold=bold)
    return p


def add_section(doc, text):
    """章节小标题：不套标题样式，与正文同字号、同字体，仅加粗，保持平铺直叙。"""
    return add_para(doc, text, size=11, bold=True, east=SONG, space_after=6)


def add_table(doc, headers, rows, caption=None, bold_if=None, col_widths=None):
    if caption:
        add_para(doc, caption, size=10.5, bold=True, indent=False, space_after=4)
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"
    hdr = t.rows[0].cells
    for i, htext in enumerate(headers):
        hdr[i].text = ""
        r = hdr[i].paragraphs[0].add_run(htext)
        _set_run_font(r, east=HEI, size=9, bold=True)
    for row in rows:
        cells = t.add_row().cells
        bold_row = bold_if(row) if bold_if else False
        for i, val in enumerate(row):
            cells[i].text = ""
            r = cells[i].paragraphs[0].add_run(str(val))
            _set_run_font(r, size=9, bold=bold_row)
    doc.add_paragraph()
    return t


